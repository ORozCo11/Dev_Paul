import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
let defaultRequests = 0; page.on('request',request=>{if(request.url().endsWith('/api/impersonate/default')) defaultRequests += 1;});
page.setDefaultTimeout(20000);const errors=[];page.on('pageerror',e=>{errors.push(e.message);console.log('PAGEERROR',e.message);});
await page.goto('http://localhost:5173/login');
await page.locator('input[name=email]').fill('impersonation@test.com');
await page.locator('input[name=password]').fill('test123');
await page.getByRole('button',{name:'Sign in',exact:true}).click();
await page.waitForURL('**/admin');
await page.getByRole('button',{name:'Switch account',exact:true}).waitFor();
assert.equal(await page.getByRole('heading',{name:'Choose an account',exact:true}).count(),0);
assert.equal(await page.evaluate(() => localStorage.getItem('impersonator_role')),'Impersonator');
await page.reload();await page.getByRole('button',{name:'Switch account',exact:true}).waitFor();
await page.getByRole('button',{name:'Switch account',exact:true}).click();
await page.getByRole('heading',{name:'Choose an account',exact:true}).waitFor();
assert.equal(new URL(page.url()).searchParams.get('choose'),'1');
await page.getByRole('row').filter({has:page.getByText('admin@barangay.gov',{exact:true})}).waitFor();
assert.equal(await page.getByRole('button',{name:'Barangay Management',exact:true}).count(),0);
await page.screenshot({path:'logs/impersonation-hub-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});await page.screenshot({path:'logs/impersonation-hub-mobile.png',fullPage:true});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
await page.setViewportSize({width:1440,height:1000});
await page.getByRole('searchbox',{name:'Search accounts'}).fill('admin@barangay.gov');
await page.getByRole('row').filter({has:page.getByText('admin@barangay.gov',{exact:true})}).getByRole('button',{name:'Impersonate',exact:true}).click();
await page.waitForURL('**/admin');
await page.getByRole('button',{name:'Switch account',exact:true}).click();
await page.getByRole('heading',{name:'Choose an account',exact:true}).waitFor();
await page.getByRole('row').filter({has:page.getByText('superadmin@barangay.gov',{exact:true})}).getByRole('button',{name:'Impersonate',exact:true}).click();
await page.waitForURL('**/superadmin');await page.getByRole('button',{name:'Switch account',exact:true}).click();
await page.getByRole('heading',{name:'Choose an account',exact:true}).waitFor();
await page.reload();await page.getByRole('heading',{name:'Choose an account',exact:true}).waitFor();
await page.getByRole('button',{name:'Sign out',exact:true}).click();await page.waitForURL('**/login');
assert.equal(defaultRequests,1);assert.deepEqual(errors,[]);console.log(JSON.stringify({passed:true,checks:['Sign-in opens default Admin directly without the chooser','Accounts across barangays listed','Mobile layout','Search','One-click Admin login and return','One-click Super Admin login and return','Admin reload stays signed in; manual chooser reload and sign out'],pageErrors:errors}));await browser.close();
